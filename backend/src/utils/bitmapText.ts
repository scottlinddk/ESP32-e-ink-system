const ACCENTED = new Set(Array.from('ÀÁÂÃÄÈÉÊËÌÍÎÏÑÒÓÔÕÖÙÚÛÜÝŸàáâãäèéêëìíîïñòóôõöùúûüýÿ'));
const ACCENTS: Readonly<Record<string, readonly [number, number]>> = {
  '\u0300': [0x06, 0x0c], // grave
  '\u0301': [0x18, 0x0c], // acute
  '\u0302': [0x0c, 0x12], // circumflex
  '\u0303': [0x16, 0x0d], // tilde
  '\u0308': [0x12, 0x00], // diaeresis
};

export function normalizeBitmapText(text: string): string {
  return text.normalize('NFC');
}

export function bitmapGlyph(codePoint: number, ascii: readonly Glyph[]): Glyph {
  if (codePoint >= 32 && codePoint <= 126) return ascii[codePoint - 32];
  // NBSP has a blank glyph, but remains part of a word during wrapping.
  if (codePoint === 0xa0) return ascii[0];
  const character = Number.isInteger(codePoint) && codePoint >= 0 && codePoint <= 0x10ffff
    ? String.fromCodePoint(codePoint) : '';
  if (GLYPHS[character]) return GLYPHS[character];
  if (ACCENTED.has(character)) {
    const [base, accent] = Array.from(character.normalize('NFD'));
    const glyph = ascii[base.codePointAt(0)! - 32];
    const marks = ACCENTS[accent];
    // Reserve two rows for the accent; retain the lowercase body/descender.
    const body = base === base.toLowerCase()
      ? glyph.slice(2) : [glyph[0], glyph[1], glyph[2], glyph[3], glyph[4], glyph[6]];
    return [...marks, ...body];
  }
  return ascii[63 - 32]; // One visible '?' for each unsupported code point.
}

// Yield lazily so a small clipped widget never lays out an entire long article.
export function* wrapBitmapText(text: string, maxCharacters: number): Generator<string> {
  if (!Number.isInteger(maxCharacters) || maxCharacters < 1 || text.length === 0) return;
  for (const paragraph of normalizeBitmapText(text).split(/\r\n?|\n/u)) {
    let line: string[] = [];
    for (const word of paragraph.split(/[ \t]+/u).filter(Boolean)) {
      const characters = Array.from(word);
      if (line.length > 0 && line.length + 1 + characters.length > maxCharacters) {
        yield line.join('');
        line = [];
      }
      if (line.length > 0) line.push(' ');
      let offset = 0;
      while (characters.length - offset > maxCharacters) {
        yield characters.slice(offset, offset + maxCharacters).join('');
        offset += maxCharacters;
      }
      line.push(...characters.slice(offset));
    }
    yield line.join('');
  }
}
