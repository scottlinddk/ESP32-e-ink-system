// Builds src/services/calendarWorker.bundle.cjs: the calendar parser worker with node-ical and
// its dependencies inlined. The deployed worker then loads nothing from node_modules, so it does
// not depend on how the hosting platform packages dependencies. Run after changing the worker or
// upgrading node-ical: `npm run build:calendar-worker -w backend`. A test fails if it is stale.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const backend = join(dirname(fileURLToPath(import.meta.url)), '..');
export const bundlePath = join(backend, 'src/services/calendarWorker.bundle.cjs');

export async function buildCalendarWorker() {
  const require = createRequire(join(backend, 'package.json'));
  const zones = await readFile(join(dirname(require.resolve('node-ical/package.json')), 'windowsZones.json'), 'utf8');
  const result = await build({
    entryPoints: [join(backend, 'src/services/calendarWorker.cjs')],
    absWorkingDir: backend, bundle: true, platform: 'node', format: 'cjs', target: 'node22',
    define: { CALENDAR_WINDOWS_ZONES: JSON.stringify(JSON.parse(zones)) },
    legalComments: 'eof', write: false, logLevel: 'silent',
    banner: { js: '// Generated by scripts/build-calendar-worker.mjs from calendarWorker.cjs. Do not edit.' },
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(bundlePath, await buildCalendarWorker());
  console.log(`Wrote ${bundlePath}`);
}
